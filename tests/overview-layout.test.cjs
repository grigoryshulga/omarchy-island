const assert = require('node:assert/strict');
const model = require('../plugin/OverviewModel.mjs');
const settings = require('../plugin/SettingsModel.mjs');
const {ordered} = require('../plugin/ModuleCatalog.mjs');
const defs = ordered('overview');
const defaults = model.layout(defs, []);
assert.deepEqual(defaults.map(r => r.id), ['controls','media','battery','agentLimits','t3','herdr','codex','notifications','downloads']);
assert(defaults.every(r => r.visible && r.size === 'standard'));
assert.deepEqual(model.supported(defs.find(r => r.id === 'controls')), ['minimal','standard','large']);
assert.deepEqual(model.supported(defs.find(r => r.id === 'agentLimits')), ['compact','standard']);
const compactLimits = model.update(defs, [], 'agentLimits', {size:'compact'}, 0);
assert.equal(model.layout(defs, JSON.parse(JSON.stringify(compactLimits))).find(r => r.id === 'agentLimits').size, 'compact');
let saved = model.update(defs, [], 'notifications', {visible:false,size:'compact'}, -1);
const moved = defaults.findIndex(row => row.id === 'notifications') - 1;
assert.equal(saved[moved].id, 'notifications');
assert.equal(saved[moved].visible, false);
assert.equal(saved[moved].size, 'compact');
assert(settings.valid('overviewLayout', saved));
assert.deepEqual(model.layout(defs, JSON.parse(JSON.stringify(saved))), saved);
assert.equal(model.layout(defs, [{id:'t3',visible:true,size:'large'}])[0].size, 'standard');
const future = {id:'future',visible:false,size:'large'};
assert.deepEqual(model.update(defs, [future], 'media', {}, -1).at(-1), future);
assert.equal(model.layout(defs, [future]).length, defaults.length);
for(const invalid of [null, {}, [{id:'media',visible:'false',size:'standard'}], [{id:'media',visible:true,size:'huge'}], [defaults[0],defaults[0]], [{id:'../media',visible:true,size:'standard'}]]) {
  assert.equal(model.valid(invalid), false);
  assert.deepEqual(model.layout(defs, invalid), defaults);
}
assert.deepEqual(model.supported({overviewSizes:['large','invented','minimal']}), ['minimal','standard','large']);
assert.equal(model.move(defs,defaults,'notifications','controls')[0].id,'notifications');
assert.equal(model.move(defs,defaults,'controls','').at(-1).id,'controls');
assert.deepEqual(model.move(defs,defaults,'controls','media'),defaults);
assert.deepEqual(model.move(defs,[future],'controls','').at(-1),future);
const geometry=[{id:'a',y:0,height:40},{id:'b',y:52,height:140},{id:'c',y:204,height:80}];
assert.equal(model.dropBefore(geometry,'b',10),'a');
assert.equal(model.dropBefore(geometry,'a',100),'b');
assert.equal(model.dropBefore(geometry,'a',160),'c');
assert.equal(model.dropBefore(geometry,'a',300),'');
console.log('Overview layout checks passed');
